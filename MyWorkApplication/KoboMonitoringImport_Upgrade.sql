SELECT MIN(TRIM(Display_Name)) Display_Name,
 CASE WHEN COUNT(DISTINCT User_ID) = 1 AND COUNT(User_ID) = COUNT(*) THEN MIN(User_ID) ELSE NULL END User_ID,
