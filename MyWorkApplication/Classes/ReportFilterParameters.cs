using PresentationControls;
using System;
using System.Collections.Generic;
using System.Data;
using System.Globalization;
using System.Linq;
using System.Text.RegularExpressions;

namespace MyWorkApplication.Classes
{
    internal sealed class ReportFilterParameters
    {
        public readonly Dictionary<string, object> Values = new Dictionary<string, object>();

        internal static string GridText(IEnumerable<string> columns, string text, bool wholeWord, string existingFilter)
        {
            if (string.IsNullOrWhiteSpace(text)) return existingFilter ?? "";
            string value = text.Replace("'", "''");
            if (!wholeWord)
                value = string.Concat(value.Select(character => "[]*%".Contains(character)
                    ? "[" + character + "]" : character.ToString()));
            var expressions = columns.Distinct().Select(column =>
                "Convert([" + column.Replace("\\", "\\\\").Replace("]", "\\]") + "], 'System.String') "
                + (wholeWord ? "= '" + value + "'" : "LIKE '%" + value + "%'")).ToArray();
            if (expressions.Length == 0) return existingFilter ?? "";
            string filter = "(" + string.Join(" OR ", expressions) + ")";
            return string.IsNullOrEmpty(existingFilter) ? filter : "(" + existingFilter + ") AND " + filter;
        }

        internal static IDictionary<string, IDictionary<string, object>> ForApplicationExport(DataTable rows, IEnumerable<string> cities)
        {
            var parameters = new Dictionary<string, IDictionary<string, object>>();
            foreach (string city in cities)
            {
                // IDs come from the filtered report snapshot, never from free-form SQL input.
                string[] ids = rows.Rows.Cast<DataRow>().Where(row => (string)row["City"] == city)
                    .Select(row => Convert.ToInt64(row["ID"]).ToString(CultureInfo.InvariantCulture)).Distinct().ToArray();
                parameters.Add(city, new Dictionary<string, object>
                {
                    { "@MyCondition", ids.Length == 0 ? " WHERE 1 = 0 "
                        : " WHERE Current_State = 1 AND PMP_ID IN (" + string.Join(",", ids) + ")" }
                });
            }
            return parameters;
        }

        public string Add(object value)
        {
            string name = "@report" + Values.Count;
            Values.Add(name, value);
            return name;
        }

        public string Selected(PresentationControls.CheckBoxComboBox combo)
        {
            List<string> names = new List<string>();
            foreach (var item in combo.CheckBoxItems)
                if (item.Checked) names.Add(Add(item.Text.Trim()));
            return names.Count == 0 ? "NULL" : string.Join(",", names);
        }

        // These fragments are generated by the existing date/amount controls, never SQL
        // supplied by the user. Bind the endpoints while retaining their existing predicates.
        public string Range(string fragment)
        {
            return Regex.Replace(fragment, @"(?i)\bbetween\s+('(?<startDate>\d{4}/\d{2}/\d{2})'|(?<startNumber>-?[\d.,]+))\s+and\s+('(?<endDate>\d{4}/\d{2}/\d{2})'|(?<endNumber>-?[\d.,]+))", match =>
            {
                if (match.Groups["startDate"].Success)
                    return "BETWEEN " + Add(DateTime.ParseExact(match.Groups["startDate"].Value, "yyyy/MM/dd", CultureInfo.InvariantCulture))
                        + " AND " + Add(DateTime.ParseExact(match.Groups["endDate"].Value, "yyyy/MM/dd", CultureInfo.InvariantCulture));
                return "BETWEEN " + Add(decimal.Parse(match.Groups["startNumber"].Value, CultureInfo.CurrentCulture))
                    + " AND " + Add(decimal.Parse(match.Groups["endNumber"].Value, CultureInfo.CurrentCulture));
            });
        }
    }
}
