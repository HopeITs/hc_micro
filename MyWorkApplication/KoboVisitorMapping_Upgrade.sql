INSERT INTO kobo_user_mapping
(Kobo_Form_UID, Kobo_Name, Display_Name, User_ID, Is_Ignored)
SELECT s.Kobo_Form_UID, LOWER(TRIM(s.Kobo_Name)), s.Display_Name, u.UserID, s.Is_Ignored
FROM tmp_kobo_users s
LEFT JOIN `user` u ON BINARY u.UserName = BINARY s.Local_User_Name
WHERE s.LocalDatabase = DATABASE()
ON DUPLICATE KEY UPDATE
  Display_Name = VALUES(Display_Name),
  User_ID = COALESCE(kobo_user_mapping.User_ID, VALUES(User_ID)),
  Is_Ignored = VALUES(Is_Ignored);
