-- Only seeds belonging to DATABASE() are applied. No accounts are created.
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS kobo_opening_field_mapping (
  Kobo_Form_UID VARCHAR(100) NOT NULL PRIMARY KEY,
  Project_Number_Field VARCHAR(255) NOT NULL,
  Visitor_Choice_Field VARCHAR(255) NOT NULL,
  Visitor_Text_Field VARCHAR(255) NOT NULL,
  Vehicle_Number_Field VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS kobo_user_mapping (
  ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  Kobo_Form_UID VARCHAR(100) NOT NULL DEFAULT '',
  Kobo_Name VARCHAR(200) COLLATE utf8mb4_bin NOT NULL,
  Display_Name VARCHAR(255) NOT NULL,
  User_ID INT NULL,
  Is_Ignored TINYINT(1) NOT NULL DEFAULT 0,
  Is_Active TINYINT(1) NOT NULL DEFAULT 1,
  UNIQUE KEY uq_kobo_user_mapping (Kobo_Form_UID, Kobo_Name),
  KEY idx_kobo_user_mapping_user (User_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- User_ID is deliberately nullable and has no user FK: removed accounts do not remove names.
CREATE TABLE IF NOT EXISTS kobo_visit_visitor (
  ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  Submission_ID INT NOT NULL,
  Visitor_Order INT NOT NULL,
  Kobo_Name TEXT NOT NULL,
  Display_Name TEXT NOT NULL,
  User_ID INT NULL,
  UNIQUE KEY uq_kobo_visit_visitor (Submission_ID, Visitor_Order),
  CONSTRAINT fk_kobo_visit_visitor_submission FOREIGN KEY (Submission_ID)
    REFERENCES kobo_submission (ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

